"""Exploratory data analysis for both datasets.

Run:  python ml/eda.py
Prints summaries to stdout; the same text is written to ml/EDA_SUMMARY.md
(kept in the repo so the numbers in the README can be checked).
"""

from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "ml"))

from predict import RISK_FEATURES, RISK_TARGET_COL, age_days_to_years  # noqa: E402


def section(lines: list[str], title: str) -> None:
    lines.append("")
    lines.append(f"## {title}")
    lines.append("")


def main() -> None:
    lines: list[str] = ["# EDA Summary — Liver Cirrhosis Prediction",
                        "", "Generated by `ml/eda.py`."]

    # ---- Dataset 1: cirrhosis.csv (Mayo Clinic PBC) -----------------------
    df = pd.read_csv(ROOT / "ml" / "data" / "cirrhosis.csv")
    section(lines, "Dataset 1 — cirrhosis.csv (Mayo Clinic PBC data)")
    lines.append(f"- Rows: {len(df)}, columns: {len(df.columns)}")
    lines.append(f"- Columns: {', '.join(df.columns)}")
    lines.append("")
    lines.append("### Target — Stage (1–4)")
    lines.append("")
    lines.append("```")
    lines.append(str(df["Stage"].value_counts(dropna=False).sort_index()))
    lines.append("```")
    lines.append("")
    lines.append("- 6 rows have no Stage and are dropped before training "
                 f"(412 usable rows).")
    lines.append("")
    lines.append("### Age is in DAYS, not years (critical)")
    lines.append("")
    lines.append(f"- Age range: {df['Age'].min():.0f}–{df['Age'].max():.0f} days "
                 f"= {age_days_to_years(df['Age'].min()):.1f}–"
                 f"{age_days_to_years(df['Age'].max()):.1f} years.")
    lines.append("- The original app.py form expects age in YEARS (26–78). "
                 "Training converts Age/365.25; see ml/predict.py.")
    lines.append("")
    lines.append("### Missing values (imputed with median for numbers, "
                 "mode for categories)")
    lines.append("")
    lines.append("```")
    lines.append(str(df.isna().sum()[df.isna().sum() > 0]))
    lines.append("```")
    lines.append("")
    lines.append("### Numeric ranges (observed — wider than app.py's comments)")
    lines.append("")
    lines.append("```")
    lines.append(str(df.describe().T[["min", "max", "mean"]].round(2)))
    lines.append("```")
    lines.append("")
    lines.append("### Category counts")
    lines.append("")
    for col in ["Drug", "Sex", "Ascites", "Hepatomegaly", "Spiders", "Edema"]:
        lines.append(f"- {col}: {df[col].value_counts(dropna=False).to_dict()}")
    lines.append("")

    # ---- Dataset 2: HealthCareData.xlsx (Kaggle) --------------------------
    section(lines, "Dataset 2 — HealthCareData.xlsx (Kaggle Indian liver data)")
    xls = pd.read_excel(ROOT / "ml" / "data" / "HealthCareData.xlsx")
    lines.append(f"- Rows: {len(xls)}, columns: {len(xls.columns)}")
    lines.append(f"- Target column: `{RISK_TARGET_COL}`")
    lines.append("")
    lines.append("### Target — extreme imbalance (read this before trusting accuracy)")
    lines.append("")
    lines.append("```")
    lines.append(str(xls[RISK_TARGET_COL].value_counts(dropna=False)))
    lines.append("```")
    lines.append("")
    lines.append("- YES 876 / no 20 / blank 54.  Blanks are dropped (896 usable "
                 "rows).  Only 2.2% of labelled rows are 'no'.")
    lines.append("- A model that always answers YES would score ~97.8% "
                 "accuracy and still be useless.  That is why the risk model "
                 "is judged on per-class precision/recall, not raw accuracy, "
                 "and uses `class_weight='balanced'` where supported.")
    lines.append("")
    lines.append("### Curated risk features (16 of 41 columns)")
    lines.append("")
    for col, _key in RISK_FEATURES:
        lines.append(f"- {col}")
    lines.append("")
    lines.append("The other 25 columns are mostly near-duplicates of these "
                 "(e.g. Direct/Indirect Bilirubin repeat Total Bilirubin; "
                 "MCV/MCH/MCHC repeat the haemoglobin picture; Total Protein "
                 "and Globulin repeat Albumin).  See ml/train_risk.py for the "
                 "feature-importance check that justifies the subset.")
    lines.append("")
    lines.append("### Missing values in the risk subset")
    lines.append("")
    lines.append("```")
    sub = xls[[c for c, _ in RISK_FEATURES] + [RISK_TARGET_COL]]
    lines.append(str(sub.isna().sum()[sub.isna().sum() > 0]))
    lines.append("```")

    text = "\n".join(lines) + "\n"
    (ROOT / "ml" / "EDA_SUMMARY.md").write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
